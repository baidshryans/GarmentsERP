"""
Shared ERP tool registry
=========================
Single source of truth for the AI-callable ERP tools. The exact same Python
functions power two front doors:

  * mcp_server.py          — exposes them over MCP to external clients
                             (Claude Desktop / Claude Code / SSE).
  * ai_layer/services/     — exposes them to the in-app ERP chat via the
    nl_query.py              Anthropic Messages API.

Because both import the identical function objects, the two can never drift
apart: fix a query here and both the MCP server and the chat are fixed.

The Claude-facing tool schemas are generated by introspection, so adding a new
@mcp.tool() to mcp_server.py automatically flows through — just add its name to
TOOL_NAMES below.
"""

import inspect
import json

# Importing mcp_server registers the tools with FastMCP as a side effect, but the
# functions themselves remain plain callables (FastMCP's @tool() returns the
# original function unchanged). Django is already configured in the web process,
# so mcp_server's bootstrap is a guarded no-op.
import mcp_server as _erp


