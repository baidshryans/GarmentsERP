# name -> callable
REGISTRY = {name: getattr(_erp, name) for name in TOOL_NAMES}

# Parameter injected server-side (scoped to the logged-in user's retail) and
# therefore hidden from the model — the chat must never let Claude pick a branch.
_INJECTED_PARAMS = {"retail_code"}

_PY_TO_JSON = {"str": "string", "int": "integer", "float": "number", "bool": "boolean"}


def _json_type(annotation) -> str:
    name = getattr(annotation, "__name__", str(annotation))
    return _PY_TO_JSON.get(name, "string")


def _anthropic_schema(fn) -> dict:
    """Build an Anthropic tool schema from a function's signature + docstring."""
    sig = inspect.signature(fn)
    props, required = {}, []
    for pname, param in sig.parameters.items():
        if pname in _INJECTED_PARAMS:
            continue
        props[pname] = {"type": _json_type(param.annotation)}
        if param.default is inspect.Parameter.empty:
            required.append(pname)
    return {
        "name": fn.__name__,
        "description": inspect.getdoc(fn) or fn.__name__,
        "input_schema": {
            "type": "object",
            "properties": props,
            "required": required,
        },
    }


# Cached list of Claude tool definitions (built once at import).
ANTHROPIC_TOOLS = [_anthropic_schema(REGISTRY[name]) for name in TOOL_NAMES]


def dispatch(name: str, args: dict, retail) -> dict:
    """
    Execute a tool by name. `retail` is the logged-in user's RetailMaster; its
    retail_code is injected if the tool accepts one. Tool functions return a JSON
    string (their MCP contract); we parse it back to a dict for the chat.
    """
    fn = REGISTRY.get(name)
    if fn is None:
        return {"error": f"Unknown tool: {name}"}

    call_args = dict(args or {})
    if "retail_code" in inspect.signature(fn).parameters:
        code = getattr(retail, "retail_code", "") or ""
        call_args["retail_code"] = code

    try:
        result = fn(**call_args)
    except Exception as exc:  # surfaced to the model so it can explain gracefully
        return {"error": f"{type(exc).__name__}: {exc}"}

    if isinstance(result, str):
        try:
            return json.loads(result)
        except (ValueError, TypeError):
            return {"result": result}
    return result


def assert_registry_in_sync():
    """
    Fail loud if mcp_server registers a tool that isn't in TOOL_NAMES (drift
    guard). Call from a test or a management check.
    """
    registered = set()
    tm = getattr(_erp.mcp, "_tool_manager", None)
    tools = getattr(tm, "_tools", None) if tm else None
    if isinstance(tools, dict):
        registered = set(tools.keys())
    missing = registered - set(TOOL_NAMES)
    if missing:
        raise AssertionError(
            f"MCP tools not exposed to the chat registry: {sorted(missing)}"
        )
    return sorted(registered)
